CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL,
    country_code CHAR(2) NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),

    CONSTRAINT uq_cities_country_name UNIQUE (country_code, name)
);

CREATE TABLE interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    name VARCHAR(100) NOT NULL UNIQUE
);

-- Fails on purpose if profile rows already exist: there is no meaningful default for these columns.
ALTER TABLE user_profiles
    ADD COLUMN date_of_birth DATE NOT NULL,
    ADD COLUMN city_id BIGINT NOT NULL REFERENCES cities(id),
    ALTER COLUMN first_name SET NOT NULL,
    ALTER COLUMN bio TYPE VARCHAR(1000),
    ADD CONSTRAINT ck_user_profiles_first_name_not_blank CHECK (btrim(first_name) <> ''),
    ADD CONSTRAINT ck_user_profiles_last_name_not_blank CHECK (last_name IS NULL OR btrim(last_name) <> '');

CREATE TABLE user_interests (
    user_id UUID NOT NULL REFERENCES user_profiles(user_id) ON DELETE CASCADE,
    interest_id BIGINT NOT NULL REFERENCES interests(id) ON DELETE RESTRICT,

    PRIMARY KEY (user_id, interest_id)
);

CREATE INDEX idx_user_interests_interest_id ON user_interests(interest_id);
CREATE INDEX idx_user_profiles_city_id ON user_profiles(city_id);
